package main

import "fmt"

func main() {

	/**
	 * Basic Data Types in Go
	 */

	/**
	 * 1. Integer (int)
	 *    - Represents whole numbers.
	 *    - Example: 1, 10, 100
	 */
	fmt.Println(1 + 1)

	/**
	 * 2. String (string)
	 *    - Represents text.
	 *    - Example: "hello golang"
	 */
	fmt.Println("hello golang")

	/**
	 * 3. Boolean (bool)
	 *    - Represents either true or false.
	 *    - Example: true, false
	 */
	fmt.Println(true)
	fmt.Println(false)

	/**
	 * 4. Float (float)
	 *    - Represents numbers with decimal values.
	 *    - Example: 10.5, 7.25
	 */
	fmt.Println(10.5)
	fmt.Println(7.0 / 3.0)
}